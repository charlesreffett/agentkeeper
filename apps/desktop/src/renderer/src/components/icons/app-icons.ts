import { Icon } from '@iconify/vue'
import { defineComponent, h } from 'vue'

function createAppIcon(name: string) {
  return defineComponent({
    name,
    inheritAttrs: false,
    setup(_, { attrs }) {
      return () => h(Icon, { icon: `lucide:${name}`, ...attrs })
    },
  })
}

